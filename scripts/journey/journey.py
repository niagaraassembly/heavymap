#!/usr/bin/env python3
"""HeavyMap Journey publisher: Telegraph pages in Telepatch's format, with local copies.

    journey.py init                         create the Journey index and section collections
    journey.py post FILE --section S        publish a post and file it in a section
    journey.py post FILE --section S --dry-run   parse and check only
    journey.py edit JP-0001 FILE            replace a post's content (path stays)
    journey.py wipe JP-0001                 replace a post with a placeholder
    journey.py snapshot [JP-0001 ...]       refresh local copies from Telegraph
    journey.py check FILE                   run the pre-send check only

Design: heavymap-restricted docs/2026-11-18-journey-and-expansion-posts.md (D-088..D-093).
The token is read from ~/.config/heavymap/telegraph.env and is never printed.
Local copies (source, Telegraph JSON, media) and the register live in journey/ at the repo
root, so the site can be rebuilt without Telegraph.
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import hashlib
import json
import os
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://api.telegra.ph"
ROOT = Path(__file__).resolve().parents[2]
JOURNEY = ROOT / "journey"
REGISTER = JOURNEY / "register.csv"
COLLECTIONS = JOURNEY / "collections.json"
PAGES = JOURNEY / "pages"
TOKEN_FILE = Path.home() / ".config/heavymap/telegraph.env"

MASTER_MARK = "Index generated by Telepatch."
INDEX_SEP = " — "
COLOPHON_MARK = "heavymap-journey/1"
PROVENANCE = "Prepared with Claude (Anthropic) · model Claude Opus 5.5 · {date}"
SECTIONS = {
    "origins": ("Origins", "Where HeavyMap came from: the UK atlas, the first Hamilton–Niagara attempt, and why we started again."),
    "expansion": ("Expansion", "Reports from each city run. Every run follows the same written method, and every run changes it a little."),
    "systems": ("Systems", "The machinery behind HeavyMap: the Assembly System, MAKE, Dispatch, Join, and the frameworks they rest on."),
}
WORDS_PER_MINUTE = 220
EXCERPT_LIMIT = 220

REGISTER_COLUMNS = [
    "post_id", "kind", "title", "telegraph_path", "telegraph_url", "site_path",
    "section", "type", "run_id", "stage", "seq", "method_version", "tags",
    "place_ids", "place_type", "country", "subdivision", "county", "city",
    "created_at", "last_edited_at", "revision", "content_hash", "status", "wiped_at",
    "supersedes", "superseded_by", "gate_class", "check_result", "hold_rules_hit", "approved_by",
    "word_count", "read_minutes", "images", "embeds", "sources", "evidence_date", "language",
    "collections", "views", "views_checked_at", "related_records", "notes",
]

# ---------------------------------------------------------------- Telegraph


def token() -> str:
    for line in TOKEN_FILE.read_text().splitlines():
        if line.startswith("TELEGRAPH_ACCESS_TOKEN="):
            return line.split("=", 1)[1].strip()
    raise SystemExit(f"no token in {TOKEN_FILE}")


def api(method: str, **params) -> dict:
    data = urllib.parse.urlencode({k: v for k, v in params.items() if v is not None}).encode()
    req = urllib.request.Request(f"{API}/{method}", data=data, headers={"User-Agent": "heavymap-journey/1"})
    with urllib.request.urlopen(req, timeout=30) as r:
        out = json.load(r)
    if not out.get("ok"):
        raise SystemExit(f"Telegraph {method} failed: {out.get('error')}")
    return out["result"]


def get_page(path: str) -> dict:
    return api("getPage", path=path, return_content="true")


# ---------------------------------------------------------------- post format

INLINE = re.compile(r"(\*\*(.+?)\*\*|\*(.+?)\*|`(.+?)`|\[([^\]]+)\]\((https?://[^)\s]+)\))")
IMAGE_LINE = re.compile(r"^(https?://\S+\.(?:png|jpe?g|gif|webp|svg))(?:\s+(.*))?$", re.I)


def inline(text: str) -> list:
    out, at = [], 0
    for m in INLINE.finditer(text):
        if m.start() > at:
            out.append(text[at:m.start()])
        if m.group(2):
            out.append({"tag": "strong", "children": inline(m.group(2))})
        elif m.group(3):
            out.append({"tag": "em", "children": inline(m.group(3))})
        elif m.group(4):
            out.append({"tag": "code", "children": [m.group(4)]})
        else:
            out.append({"tag": "a", "attrs": {"href": m.group(6)}, "children": [m.group(5)]})
        at = m.end()
    if at < len(text):
        out.append(text[at:])
    return out


def parse_post(text: str) -> dict:
    """Title line, tag line, optional '> ' standfirst, then a small Markdown body."""
    lines = text.replace("\r\n", "\n").split("\n")
    meta = {}
    if lines and lines[0].strip() == "---":  # optional colophon fields as front matter
        end = lines.index("---", 1)
        for raw in lines[1:end]:
            if ":" in raw:
                k, v = raw.split(":", 1)
                meta[k.strip()] = v.strip()
        lines = lines[end + 1:]
    while lines and not lines[0].strip():
        lines.pop(0)
    title = lines.pop(0).strip()
    tags = [t.strip() for t in lines.pop(0).split(",") if t.strip()]
    while lines and not lines[0].strip():
        lines.pop(0)
    intro = None
    if lines and lines[0].startswith("> "):
        buf = []
        while lines and lines[0].startswith(">"):
            buf.append(lines.pop(0)[1:].strip())
        intro = " ".join(buf)

    nodes, para, i = [], [], 0

    def flush():
        if para:
            nodes.append({"tag": "p", "children": inline(" ".join(para))})
            para.clear()

    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s:
            flush(); i += 1; continue
        if s.startswith("```"):
            flush(); i += 1; buf = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                buf.append(lines[i]); i += 1
            nodes.append({"tag": "pre", "children": ["\n".join(buf)]}); i += 1; continue
        if s.startswith("### "):
            flush(); nodes.append({"tag": "h4", "children": inline(s[4:])}); i += 1; continue
        if s.startswith("## ") or s.startswith("# "):
            flush(); nodes.append({"tag": "h3", "children": inline(s.split(" ", 1)[1])}); i += 1; continue
        if s == "---":
            flush(); nodes.append({"tag": "hr"}); i += 1; continue
        if s.startswith("> "):
            flush(); buf = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                buf.append(lines[i].strip()[1:].strip()); i += 1
            nodes.append({"tag": "blockquote", "children": inline(" ".join(buf))}); continue
        m = IMAGE_LINE.match(s)
        if m:
            flush()
            fig = [{"tag": "img", "attrs": {"src": m.group(1)}}]
            if m.group(2):
                fig.append({"tag": "figcaption", "children": inline(m.group(2))})
            nodes.append({"tag": "figure", "children": fig}); i += 1; continue
        if re.match(r"^[-*] ", s) or re.match(r"^\d+\. ", s):
            flush(); ordered = bool(re.match(r"^\d+\. ", s)); items = []
            while i < len(lines) and (re.match(r"^\s*[-*] ", lines[i]) or re.match(r"^\s*\d+\. ", lines[i])):
                items.append({"tag": "li", "children": inline(re.sub(r"^\s*(?:[-*]|\d+\.) ", "", lines[i]))}); i += 1
            nodes.append({"tag": "ol" if ordered else "ul", "children": items}); continue
        para.append(s); i += 1
    flush()
    return {"title": title, "tags": tags, "intro": intro, "body": nodes, "meta": meta}


def node_text(n) -> str:
    if isinstance(n, str):
        return n
    return "".join(node_text(c) for c in n.get("children") or [])


def build_content(post: dict, colophon: dict, today: str) -> list:
    content = [{"tag": "aside", "children": [", ".join(post["tags"])]}]
    if post["intro"]:
        content.append({"tag": "blockquote", "children": inline(post["intro"])})
    content += post["body"]
    content.append({"tag": "p", "children": [{"tag": "em", "children": [PROVENANCE.format(date=today)]}]})
    content.append({"tag": "hr"})
    lines = [COLOPHON_MARK] + [f"{k}: {v}" for k, v in colophon.items()]
    content.append({"tag": "pre", "children": ["\n".join(lines)]})
    return content


def words(nodes) -> int:
    return len(" ".join(node_text(n) for n in nodes).split())


def excerpt(post: dict) -> str:
    text = post["intro"] or next((node_text(n) for n in post["body"] if isinstance(n, dict) and n.get("tag") == "p"), "")
    return text if len(text) <= EXCERPT_LIMIT else text[:EXCERPT_LIMIT].rsplit(" ", 1)[0] + "…"


# ---------------------------------------------------------------- pre-send check

BLOCK = [
    ("H3 email address", re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")),
    ("H3 home path", re.compile(r"/home/\w+|/Users/\w+")),
    ("H3 token-like string", re.compile(r"\b(?=[A-Za-z0-9]*\d)(?=[A-Za-z0-9]*[A-Za-z])[A-Za-z0-9]{40,}\b")),
    ("H3 private repository", re.compile(r"heavymap-portraits|heavymap-restricted|service-data|PORTRAITS_DEPLOY_KEY")),
    ("H1 phone number", re.compile(r"\(?\b\d{3}\)?[ .-]\d{3}[ .-]\d{4}\b")),
]
REVIEW = [
    ("H2 portrait files", re.compile(r"portrait", re.I)),
    ("H1 owner values", re.compile(r"owner name|owner_name|registered owner", re.I)),
    ("H4 commercial", re.compile(r"pricing|customer|investor|fundrais", re.I)),
    ("H7 unverified claim", re.compile(r"\ballegedly\b|\brumou?r", re.I)),
]


def check(text: str) -> tuple[str, list]:
    hits = [name for name, rx in BLOCK if rx.search(text)]
    if hits:
        return "blocked", hits
    soft = [name for name, rx in REVIEW if rx.search(text)]
    return ("review" if soft else "pass"), soft


# ---------------------------------------------------------------- local records


def read_register() -> list[dict]:
    if not REGISTER.exists():
        return []
    with REGISTER.open(newline="") as f:
        return list(csv.DictReader(f))


def write_register(rows: list[dict]) -> None:
    JOURNEY.mkdir(exist_ok=True)
    with REGISTER.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=REGISTER_COLUMNS, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in REGISTER_COLUMNS})


def next_id(rows) -> str:
    n = max([int(r["post_id"][3:]) for r in rows if r["post_id"].startswith("JP-")] or [0])
    return f"JP-{n + 1:04d}"


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()


def save_copy(page: dict, source: str | None = None) -> str:
    """Telegraph JSON (+ our source) under journey/pages/<path>/; images copied to media/."""
    d = PAGES / page["path"]
    d.mkdir(parents=True, exist_ok=True)
    blob = json.dumps(page, ensure_ascii=False, indent=1, sort_keys=True)
    (d / "page.json").write_text(blob + "\n")
    if source is not None:
        (d / "source.md").write_text(source)
    for src in image_sources(page.get("content") or []):
        url = src if src.startswith("http") else "https://telegra.ph" + src
        name = re.sub(r"[^\w.-]", "_", urllib.parse.urlparse(url).path.rsplit("/", 1)[-1])[:120] or "image"
        (d / "media").mkdir(exist_ok=True)
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "heavymap-journey/1"}), timeout=30) as r:
                (d / "media" / name).write_bytes(r.read())
        except Exception as e:  # keep going; the register notes it
            print(f"  image not copied: {url} ({e})", file=sys.stderr)
    return hashlib.sha256(json.dumps(page.get("content"), sort_keys=True).encode()).hexdigest()


def image_sources(nodes):
    for n in nodes:
        if isinstance(n, dict):
            if n.get("tag") in ("img", "video") and (n.get("attrs") or {}).get("src"):
                yield n["attrs"]["src"]
            yield from image_sources(n.get("children") or [])


def collections() -> dict:
    return json.loads(COLLECTIONS.read_text()) if COLLECTIONS.exists() else {}


# ---------------------------------------------------------------- index pages


def marker(extra: bool) -> dict:
    return {"tag": "p", "children": [f"{MASTER_MARK} byline=plain" + (" collection=extra" if extra else "")]}


def entry_node(url, title, date, minutes, tags, text) -> dict:
    meta = INDEX_SEP + date + (f" · {minutes} min" if minutes else "") + (" · " + ", ".join(tags) if tags else "")
    kids = [{"tag": "a", "attrs": {"href": url}, "children": [title]}, meta]
    if text:
        kids += [{"tag": "br"}, text]
    return {"tag": "li", "children": kids}


def insert_entry(index_path: str, entry: dict, tok: str) -> None:
    page = get_page(index_path)
    content = page.get("content") or []
    at = next((i for i, n in enumerate(content) if isinstance(n, dict) and n.get("tag") == "ul"), None)
    keep = [n for n in content if MASTER_MARK not in node_text(n)]
    mark = next((n for n in content if MASTER_MARK in node_text(n)), marker(True))
    if at is None:
        empty = next((i for i, n in enumerate(keep) if node_text(n).strip() == "Nothing here yet."), None)
        listing = {"tag": "ul", "children": [entry]}
        keep = keep[:empty] + [listing] + keep[empty + 1:] if empty is not None else keep + [listing]
    else:
        listing = next(n for n in keep if isinstance(n, dict) and n.get("tag") == "ul")
        url = entry["children"][0]["attrs"]["href"]
        listing["children"] = [entry] + [li for li in listing.get("children", [])
                                         if not (isinstance(li, dict) and li.get("children") and isinstance(li["children"][0], dict)
                                                 and (li["children"][0].get("attrs") or {}).get("href") == url)]
    api("editPage", access_token=tok, path=index_path, title=page["title"], author_name="HeavyMap",
        author_url="https://heavymap.com/journey", content=json.dumps(keep + [mark], ensure_ascii=False))


# ---------------------------------------------------------------- commands


def cmd_init(args) -> None:
    tok, cols, rows = token(), collections(), read_register()
    created = False
    for key, (name, about) in [("journey", ("Journey", "Making HeavyMap, in the open: notes from building an industrial map of the world, one city at a time."))] + list(SECTIONS.items()):
        if key in cols:
            continue
        content = [{"tag": "p", "children": [about]}, {"tag": "p", "children": ["Nothing here yet."]}, marker(key != "journey")]
        if args.dry_run:
            print(f"would create index {name}"); continue
        page = api("createPage", access_token=tok, title=name if key != "journey" else "HeavyMap Journey",
                   author_name="HeavyMap", author_url="https://heavymap.com/journey",
                   content=json.dumps(content, ensure_ascii=False))
        cols[key] = {"name": name, "path": page["path"], "url": page["url"], "about": about}
        rows.append({"post_id": next_id(rows), "kind": "index" if key == "journey" else "collection", "title": page["title"],
                     "telegraph_path": page["path"], "telegraph_url": page["url"],
                     "site_path": "/journey/" if key == "journey" else f"/journey/{key}/", "section": key if key != "journey" else "",
                     "created_at": now(), "last_edited_at": now(), "revision": "1", "status": "live",
                     "content_hash": save_copy(get_page(page["path"])), "gate_class": "ungated", "check_result": "pass",
                     "language": "en"})
        created = True
        print(f"created {name}: {page['url']}")
    if created:
        # The Journey index links each section, tagged `site` for the Telepatch reader.
        reader = "https://babbworks.github.io/telepatch/#"
        today = dt.date.today().isoformat()
        j = cols["journey"]
        items = [entry_node(reader + cols[k]["path"], cols[k]["name"], today, 0, ["site"], cols[k]["about"]) for k in SECTIONS]
        api("editPage", access_token=tok, path=j["path"], title="HeavyMap Journey", author_name="HeavyMap",
            author_url="https://heavymap.com/journey",
            content=json.dumps([{"tag": "p", "children": [j["about"]]}, {"tag": "ul", "children": items}, marker(False)], ensure_ascii=False))
        COLLECTIONS.write_text(json.dumps(cols, indent=1, ensure_ascii=False) + "\n")
        write_register(rows)


def colophon_for(post: dict, section: str, post_id: str, seq: str) -> dict:
    m = post["meta"]
    out = {"id": post_id, "type": m.get("type", ""), "section": section}
    for k in ("run", "place", "places", "place_type", "stage", "method", "evidence_date", "supersedes"):
        if m.get(k):
            out[k] = m[k]
    out["seq"] = m.get("seq", seq)
    return out


def cmd_post(args) -> None:
    source = Path(args.file).read_text()
    post = parse_post(source)
    rows = read_register()
    section = args.section
    if section not in SECTIONS:
        raise SystemExit(f"unknown section {section}")
    post_id = next_id(rows)
    seq = str(1 + sum(1 for r in rows if r.get("section") == section and r.get("kind") == "post"))
    today = dt.date.today().isoformat()
    content = build_content(post, colophon_for(post, section, post_id, seq), today)
    plain = post["title"] + "\n" + "\n".join(node_text(n) for n in content)
    result, hits = check(plain)
    n_words = words(post["body"]) + len((post["intro"] or "").split())
    minutes = max(1, round(n_words / WORDS_PER_MINUTE))
    print(f"{post_id} {post['title']!r} · {n_words} words · {minutes} min · check {result}{' ' + str(hits) if hits else ''}")
    if len(json.dumps(content).encode()) > 64000:
        raise SystemExit("content over Telegraph's 64 kB limit; split the post")
    if result == "blocked" or (result == "review" and not args.accept_review):
        raise SystemExit("held: fix the post or rerun with --accept-review after a human read")
    if args.dry_run:
        return
    tok, cols = token(), collections()
    if section not in cols:
        raise SystemExit("run init first")
    page = api("createPage", access_token=tok, title=post["title"], author_name="HeavyMap",
               author_url="https://heavymap.com/journey", content=json.dumps(content, ensure_ascii=False))
    insert_entry(cols[section]["path"], entry_node(page["url"], post["title"], today, minutes, post["tags"], excerpt(post)), tok)
    full = get_page(page["path"])
    m = post["meta"]
    rows.append({
        "post_id": post_id, "kind": "post", "title": post["title"], "telegraph_path": page["path"], "telegraph_url": page["url"],
        "site_path": f"/journey/{section}/#{page['path']}", "section": section, "type": m.get("type", ""),
        "run_id": m.get("run", ""), "stage": m.get("stage", ""), "seq": m.get("seq", seq), "method_version": m.get("method", ""),
        "tags": ", ".join(post["tags"]), "place_ids": m.get("places", m.get("place", "")), "place_type": m.get("place_type", ""),
        "country": m.get("country", ""), "subdivision": m.get("subdivision", ""), "county": m.get("county", ""), "city": m.get("city", ""),
        "created_at": now(), "last_edited_at": now(), "revision": "1", "content_hash": save_copy(full, source), "status": "live",
        "supersedes": m.get("supersedes", ""), "gate_class": "ungated", "check_result": result, "hold_rules_hit": "; ".join(hits),
        "approved_by": "Morgen (review)" if result == "review" else "", "word_count": str(n_words), "read_minutes": str(minutes),
        "images": str(sum(1 for _ in image_sources(content))), "embeds": "", "sources": m.get("sources", ""),
        "evidence_date": m.get("evidence_date", ""), "language": "en", "collections": section,
        "related_records": m.get("related", ""), "notes": m.get("notes", ""),
    })
    write_register(rows)
    print(f"published {page['url']}")


def find(rows, post_id):
    r = next((r for r in rows if r["post_id"] == post_id), None)
    if not r:
        raise SystemExit(f"{post_id} not in register")
    return r


def cmd_edit(args, wipe=False) -> None:
    rows, tok = read_register(), token()
    r = find(rows, args.post_id)
    if wipe:
        content = [{"tag": "p", "children": ["This page has been withdrawn."]}]
        title, source = "Withdrawn", None
    else:
        source = Path(args.file).read_text()
        post = parse_post(source)
        today = dt.date.today().isoformat()
        content = build_content(post, colophon_for(post, r["section"], r["post_id"], r["seq"]), today)
        result, hits = check(post["title"] + "\n" + "\n".join(node_text(n) for n in content))
        if result == "blocked" or (result == "review" and not args.accept_review):
            raise SystemExit(f"held: {hits}")
        title = post["title"]
    api("editPage", access_token=tok, path=r["telegraph_path"], title=title, author_name="HeavyMap",
        author_url="https://heavymap.com/journey", content=json.dumps(content, ensure_ascii=False))
    r["last_edited_at"] = now()
    r["revision"] = str(int(r.get("revision") or 1) + 1)
    r["content_hash"] = save_copy(get_page(r["telegraph_path"]), source)
    if wipe:
        r["status"], r["wiped_at"] = "wiped", now()
    else:
        r["status"] = "revised"
    write_register(rows)
    print(f"{r['post_id']} {'wiped' if wipe else 'revised'}: {r['telegraph_url']}")


def cmd_snapshot(args) -> None:
    rows = read_register()
    for r in rows:
        if args.ids and r["post_id"] not in args.ids:
            continue
        page = get_page(r["telegraph_path"])
        r["content_hash"] = save_copy(page)
        r["views"], r["views_checked_at"] = str(page.get("views", "")), now()
        print(f"{r['post_id']} saved · {page.get('views')} views")
    write_register(rows)


def cmd_check(args) -> None:
    post = parse_post(Path(args.file).read_text())
    text = post["title"] + "\n" + (post["intro"] or "") + "\n" + "\n".join(node_text(n) for n in post["body"])
    print(check(text))


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description="HeavyMap Journey publisher")
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("init"); s.add_argument("--dry-run", action="store_true"); s.set_defaults(fn=cmd_init)
    s = sub.add_parser("post"); s.add_argument("file"); s.add_argument("--section", required=True)
    s.add_argument("--dry-run", action="store_true"); s.add_argument("--accept-review", action="store_true"); s.set_defaults(fn=cmd_post)
    s = sub.add_parser("edit"); s.add_argument("post_id"); s.add_argument("file"); s.add_argument("--accept-review", action="store_true")
    s.set_defaults(fn=lambda a: cmd_edit(a))
    s = sub.add_parser("wipe"); s.add_argument("post_id"); s.set_defaults(fn=lambda a: cmd_edit(a, wipe=True))
    s = sub.add_parser("snapshot"); s.add_argument("ids", nargs="*"); s.set_defaults(fn=cmd_snapshot)
    s = sub.add_parser("check"); s.add_argument("file"); s.set_defaults(fn=cmd_check)
    a = p.parse_args(argv)
    a.fn(a)


if __name__ == "__main__":
    main()
