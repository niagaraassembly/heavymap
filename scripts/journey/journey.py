# ---------------------------------------------------------------- Telegraph


def token() -> str:
    for line in TOKEN_FILE.read_text().splitlines():
        if line.startswith("TELEGRAPH_ACCESS_TOKEN="):
            return line.split("=", 1)[1].strip()
    raise SystemExit(f"no token in {TOKEN_FILE}")


def api(method: str, **params) -> dict:
    """One Telegraph call. FLOOD_WAIT_n means the call was refused, so waiting n seconds and
    sending it again cannot create a duplicate."""
    import time
    data = urllib.parse.urlencode({k: v for k, v in params.items() if v is not None}).encode()
    for attempt in range(6):
        req = urllib.request.Request(f"{API}/{method}", data=data, headers={"User-Agent": "heavymap-journey/1"})
        with urllib.request.urlopen(req, timeout=30) as r:
            out = json.load(r)
        if out.get("ok"):
            return out["result"]
        m = re.match(r"FLOOD_WAIT_(\d+)", str(out.get("error", "")))
        if not m or attempt == 5:
            break
        wait = int(m.group(1)) + 1
        print(f"  Telegraph asks to wait {wait} s", file=sys.stderr)
        time.sleep(wait)
    raise SystemExit(f"Telegraph {method} failed: {out.get('error')}")


# Telegraph serves a cached copy of a page for a short while after an edit, so a run that edits
# the same index twice must not re-read it: keep what each edit returned and reuse that.
_EDITED: dict = {}


def get_page(path: str) -> dict:
    if path in _EDITED:
        return _EDITED[path]
    return api("getPage", path=path, return_content="true")


def edit_page(**params) -> dict:
    page = api("editPage", return_content="true", **params)
    _EDITED[page["path"]] = page
    return page


# ---------------------------------------------------------------- post format

INLINE = re.compile(r"(\*\*(.+?)\*\*|\*(.+?)\*|`(.+?)`|\[([^\]]+)\]\((https?://[^)\s]+)\))")
IMAGE_LINE = re.compile(r"^(https?://\S+\.(?:png|jpe?g|gif|webp|svg))(?:\s+(.*))?$", re.I)


def inline(text: str) -> list:
    out, at = [], 0
    for m in INLINE.finditer(text):
        if m.start() > at:
            out.append(text[at:m.start()])
        if m.group(2):
            out.append({"tag": "strong", "children": inline(m.group(2))})
        elif m.group(3):
            out.append({"tag": "em", "children": inline(m.group(3))})
        elif m.group(4):
            out.append({"tag": "code", "children": [m.group(4)]})
        else:
            out.append({"tag": "a", "attrs": {"href": m.group(6)}, "children": [m.group(5)]})
        at = m.end()
    if at < len(text):
        out.append(text[at:])
    return out


def parse_post(text: str) -> dict:
    """Title line, tag line, optional '> ' standfirst, then a small Markdown body."""
    lines = text.replace("\r\n", "\n").split("\n")
    meta = {}
    if lines and lines[0].strip() == "---":  # optional colophon fields as front matter
        end = lines.index("---", 1)
        for raw in lines[1:end]:
            if ":" in raw:
                k, v = raw.split(":", 1)
                meta[k.strip()] = v.strip()
        lines = lines[end + 1:]
    while lines and not lines[0].strip():
        lines.pop(0)
    title = lines.pop(0).strip()
    tags = [t.strip() for t in lines.pop(0).split(",") if t.strip()]
    while lines and not lines[0].strip():
        lines.pop(0)
    intro = None
    if lines and lines[0].startswith("> "):
        buf = []
        while lines and lines[0].startswith(">"):
            buf.append(lines.pop(0)[1:].strip())
        intro = " ".join(buf)

    nodes, para, i = [], [], 0

    def flush():
        if para:
            nodes.append({"tag": "p", "children": inline(" ".join(para))})
            para.clear()

    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s:
            flush(); i += 1; continue
        if s.startswith("```"):
            flush(); i += 1; buf = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                buf.append(lines[i]); i += 1
            nodes.append({"tag": "pre", "children": ["\n".join(buf)]}); i += 1; continue
        if s.startswith("|") and i + 1 < len(lines) and re.match(r"^\|?\s*:?-{2,}", lines[i + 1].strip()):
            flush()
            split = lambda row: [c.strip().replace("\\|", "|") for c in re.split(r"(?<!\\)\|", row.strip().strip("|"))]
            head = split(s); i += 2; items = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = split(lines[i]); i += 1
                first = cells[0] if cells else ""
                rest = [f"{h}: {c}" for h, c in zip(head[1:], cells[1:]) if c and c not in ("—", "-")]
                text = (f"**{first}**" if first else "") + (" — " + " · ".join(rest) if rest else "")
                items.append({"tag": "li", "children": inline(text)})
            nodes.append({"tag": "ul", "children": items}); continue
        if re.match(r"^#{4,6} ", s):
            flush(); nodes.append({"tag": "h4", "children": inline(s.split(" ", 1)[1])}); i += 1; continue
        if s.startswith("### "):
            flush(); nodes.append({"tag": "h4", "children": inline(s[4:])}); i += 1; continue
        if s.startswith("## ") or s.startswith("# "):
            flush(); nodes.append({"tag": "h3", "children": inline(s.split(" ", 1)[1])}); i += 1; continue
        if s == "---":
            flush(); nodes.append({"tag": "hr"}); i += 1; continue
        if s.startswith("> "):
            flush(); buf = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                buf.append(lines[i].strip()[1:].strip()); i += 1
            nodes.append({"tag": "blockquote", "children": inline(" ".join(buf))}); continue
        m = IMAGE_LINE.match(s)
        if m:
            flush()
            fig = [{"tag": "img", "attrs": {"src": m.group(1)}}]
            if m.group(2):
                fig.append({"tag": "figcaption", "children": inline(m.group(2))})
            nodes.append({"tag": "figure", "children": fig}); i += 1; continue
        if re.match(r"^[-*] ", s) or re.match(r"^\d+\. ", s):
            flush(); ordered = bool(re.match(r"^\d+\. ", s)); items = []
            while i < len(lines) and (re.match(r"^\s*[-*] ", lines[i]) or re.match(r"^\s*\d+\. ", lines[i])):
                items.append({"tag": "li", "children": inline(re.sub(r"^\s*(?:[-*]|\d+\.) ", "", lines[i]))}); i += 1
            nodes.append({"tag": "ol" if ordered else "ul", "children": items}); continue
        para.append(s); i += 1
    flush()
    return {"title": title, "tags": tags, "intro": intro, "body": nodes, "meta": meta}


def node_text(n) -> str:
    if isinstance(n, str):
        return n
    return "".join(node_text(c) for c in n.get("children") or [])


def build_content(post: dict, colophon: dict, today: str) -> list:
    content = [{"tag": "aside", "children": [", ".join(post["tags"])]}]
    if post["intro"]:
        content.append({"tag": "blockquote", "children": inline(post["intro"])})
    content += post["body"]
    content.append({"tag": "p", "children": [{"tag": "em", "children": [PROVENANCE.format(date=today)]}]})
    content.append({"tag": "hr"})
    lines = [COLOPHON_MARK] + [f"{k}: {v}" for k, v in colophon.items()]
    content.append({"tag": "pre", "children": ["\n".join(lines)]})
    return content


def words(nodes) -> int:
    return len(" ".join(node_text(n) for n in nodes).split())


def excerpt(post: dict) -> str:
    text = post["intro"] or next((node_text(n) for n in post["body"] if isinstance(n, dict) and n.get("tag") == "p"), "")
    return text if len(text) <= EXCERPT_LIMIT else text[:EXCERPT_LIMIT].rsplit(" ", 1)[0] + "…"


# ---------------------------------------------------------------- pre-send check

BLOCK = [
    ("H3 email address", re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")),
    ("H3 home path", re.compile(r"(?<![\w.:/-])(?:/home/\w+|/Users/\w+)")),  # not inside web addresses
    ("H3 token-like string", re.compile(r"\b(?=[A-Za-z0-9]*\d)(?=[A-Za-z0-9]*[A-Za-z])[A-Za-z0-9]{40,}\b")),
    ("H3 private repository", re.compile(r"heavymap-portraits|heavymap-restricted|service-data|PORTRAITS_DEPLOY_KEY")),
    ("H1 phone number", re.compile(r"\(?\b\d{3}\)?[ .-]\d{3}[ .-]\d{4}\b")),
]
REVIEW = [
    ("H2 portrait files", re.compile(r"portrait", re.I)),
    ("H1 owner values", re.compile(r"owner name|owner_name|registered owner", re.I)),
    ("H4 commercial", re.compile(r"pricing|customer|investor(?!-owned)|fundrais", re.I)),  # "investor-owned utility" is a term of art
    ("H7 unverified claim", re.compile(r"\ballegedly\b|\brumou?r", re.I)),
]


CONFIG_DIR = Path.home() / ".config/heavymap"


def private_rules() -> list:
    """Private repository names and the public-repo allowlist live outside the repository
    (a list of private names in a public repo would disclose them). Refresh with
    `gh repo list niagaraassembly --json name,isPrivate`."""
    rules = []
    names = CONFIG_DIR / "journey-private-names.txt"
    public = CONFIG_DIR / "journey-public-repos.txt"
    if names.exists():
        # Only distinctive names: several private repositories are ordinary words ("publish",
        # "membership") that legitimately appear in prose.
        words = [re.escape(w) for w in names.read_text().split() if "-" in w or w in ("workwarrior",)]
        if words:
            rules.append(("H3 private repository name", re.compile(r"(?<![\w-])(?:" + "|".join(words) + r")(?![\w-])")))
    allowed = set(public.read_text().split()) if public.exists() else set()
    rules.append(("H3 repository not on the public list",
                  re.compile(r"niagaraassembly/(?!(?:" + "|".join(map(re.escape, sorted(allowed))) + r")(?![\w.-]))[\w.-]+" if allowed else r"niagaraassembly/[\w.-]+")))
    return rules


def check(text: str) -> tuple[str, list]:
    hits = [name for name, rx in BLOCK + private_rules() if rx.search(text)]
    if hits:
        return "blocked", hits
    soft = [name for name, rx in REVIEW if rx.search(text)]
    return ("review" if soft else "pass"), soft


# ---------------------------------------------------------------- local records


def read_register() -> list[dict]:
    if not REGISTER.exists():
        return []
    with REGISTER.open(newline="") as f:
        return list(csv.DictReader(f))


def write_register(rows: list[dict]) -> None:
    JOURNEY.mkdir(exist_ok=True)
    with REGISTER.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=REGISTER_COLUMNS, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in REGISTER_COLUMNS})


def next_id(rows) -> str:
    n = max([int(r["post_id"][3:]) for r in rows if r["post_id"].startswith("JP-")] or [0])
    return f"JP-{n + 1:04d}"


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()


def save_copy(page: dict, source: str | None = None) -> str:
    """Telegraph JSON (+ our source) under journey/pages/<path>/; images copied to media/."""
    d = PAGES / page["path"]
    d.mkdir(parents=True, exist_ok=True)
    blob = json.dumps(page, ensure_ascii=False, indent=1, sort_keys=True)
    (d / "page.json").write_text(blob + "\n")
    if source is not None:
        (d / "source.md").write_text(source)
    for src in image_sources(page.get("content") or []):
        url = src if src.startswith("http") else "https://telegra.ph" + src
        name = re.sub(r"[^\w.-]", "_", urllib.parse.urlparse(url).path.rsplit("/", 1)[-1])[:120] or "image"
        (d / "media").mkdir(exist_ok=True)
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "heavymap-journey/1"}), timeout=30) as r:
                (d / "media" / name).write_bytes(r.read())
        except Exception as e:  # keep going; the register notes it
            print(f"  image not copied: {url} ({e})", file=sys.stderr)
    return hashlib.sha256(json.dumps(page.get("content"), sort_keys=True).encode()).hexdigest()


def image_sources(nodes):
    for n in nodes:
        if isinstance(n, dict):
            if n.get("tag") in ("img", "video") and (n.get("attrs") or {}).get("src"):
                yield n["attrs"]["src"]
            yield from image_sources(n.get("children") or [])


def collections() -> dict:
    return json.loads(COLLECTIONS.read_text()) if COLLECTIONS.exists() else {}


# ---------------------------------------------------------------- index pages


def marker(extra: bool) -> dict:
    return {"tag": "p", "children": [f"{MASTER_MARK} byline=plain" + (" collection=extra" if extra else "")]}


def entry_node(url, title, date, minutes, tags, text) -> dict:
    meta = INDEX_SEP + date + (f" · {minutes} min" if minutes else "") + (" · " + ", ".join(tags) if tags else "")
    kids = [{"tag": "a", "attrs": {"href": url}, "children": [title]}, meta]
    if text:
        kids += [{"tag": "br"}, text]
    return {"tag": "li", "children": kids}


def norm_url(href: str) -> str:
    """Telegraph stores links to its own pages as relative paths; compare full URLs."""
    return "https://telegra.ph" + href if href.startswith("/") else href


def li_href(li) -> str:
    kids = li.get("children") if isinstance(li, dict) else None
    if kids and isinstance(kids[0], dict):
        return norm_url((kids[0].get("attrs") or {}).get("href", ""))
    return ""


def cmd_collection(args) -> None:
    """A curated sub-collection under a section, e.g. a run's field notes, with a display mode."""
    tok, cols, rows = token(), collections(), read_register()
    if args.key in cols:
        raise SystemExit(f"{args.key} exists")
    if args.parent not in SECTIONS:
        raise SystemExit(f"unknown parent section {args.parent}")
    content = [{"tag": "p", "children": [args.about]}, {"tag": "p", "children": ["Nothing here yet."]}, marker(True)]
    page = api("createPage", access_token=tok, title=args.name, author_name="HeavyMap",
               author_url="https://heavymap.com/journey", content=json.dumps(content, ensure_ascii=False))
    cols[args.key] = {"name": args.name, "path": page["path"], "url": page["url"], "about": args.about,
                      "parent": args.parent, "display": args.display, "run": args.run or ""}
    COLLECTIONS.write_text(json.dumps(cols, indent=1, ensure_ascii=False) + "\n")
    rows.append({"post_id": next_id(rows), "kind": "collection", "title": args.name, "telegraph_path": page["path"],
                 "telegraph_url": page["url"], "site_path": f"/journey/{args.parent}/{args.key}/", "section": args.parent,
                 "run_id": args.run or "", "created_at": now(), "last_edited_at": now(), "revision": "1", "status": "live",
                 "content_hash": save_copy(get_page(page["path"])), "gate_class": "ungated", "check_result": "pass",
                 "language": "en", "collections": args.parent, "notes": f"display={args.display}"})
    write_register(rows)
    rebuild_index(args.key, tok)
    rebuild_index(args.parent, tok)
    print(f"created collection {args.name}: {page['url']}")


def cmd_file(args) -> None:
    """File existing posts into a collection; --move takes them out of their other lists."""
    tok, cols, rows = token(), collections(), read_register()
    target = cols.get(args.key)
    if not target:
        raise SystemExit(f"unknown collection {args.key}")
    touched = {args.key}
    for pid in args.post_ids:
        r = find(rows, pid)
        current = [k for k in (r.get("collections") or "").split(";") if k]
        touched.update(current)
        current = [args.key] if args.move else current + ([args.key] if args.key not in current else [])
        r["collections"] = ";".join(current)
        if args.move and target.get("parent"):
            r["site_path"] = f"/journey/{target['parent']}/{args.key}/#{r['telegraph_path']}"
        r["last_edited_at"] = now()
        print(f"{pid} filed in {args.key}{' (moved)' if args.move else ''}")
    write_register(rows)
    if target.get("parent"):
        touched.add(target["parent"])
    for key in sorted(touched):
        rebuild_index(key, tok)


def parse_page_for_entry(page: dict) -> dict:
    content = page.get("content") or []
    tags = [t.strip() for t in node_text(content[0]).split(",")] if content and content[0].get("tag") == "aside" else []
    intro = node_text(content[1]) if len(content) > 1 and content[1].get("tag") == "blockquote" else ""
    return {"tags": [t for t in tags if t], "excerpt": intro if len(intro) <= EXCERPT_LIMIT else intro[:EXCERPT_LIMIT].rsplit(" ", 1)[0] + "…"}


def local_page(path: str) -> dict | None:
    f = PAGES / path / "page.json"
    return json.loads(f.read_text()) if f.exists() else None


def local_date(iso: str) -> str:
    """The date a reader in our own time zone would give the post (Telegraph has none)."""
    try:
        return dt.datetime.fromisoformat(iso).astimezone().date().isoformat()
    except ValueError:
        return dt.date.today().isoformat()


def rebuild_index(key: str, tok: str) -> None:
    """Write a section or collection index from the register, never from Telegraph's copy.

    Telegraph serves cached copies for minutes after an edit, so reading an index back and
    editing it can silently undo recent changes. The register is the source of truth: every
    post or collection whose `collections` field names this key is listed, newest first
    (oldest first for stream collections, which read in order)."""
    cols, rows = collections(), read_register()
    c = cols[key]
    items = []
    for r in rows:
        if r.get("status") == "wiped" or key not in (r.get("collections") or "").split(";"):
            continue
        if r["kind"] == "post":
            page = local_page(r["telegraph_path"]) or {}
            meta = parse_page_for_entry(page) if page.get("content") else {"tags": r["tags"].split(", "), "excerpt": ""}
            node = entry_node(r["telegraph_url"], r["title"], local_date(r["created_at"]), int(r.get("read_minutes") or 0),
                              meta["tags"], meta["excerpt"])
        elif r["kind"] == "collection":
            sub = next((k for k, v in cols.items() if v["path"] == r["telegraph_path"]), None)
            if not sub:
                continue
            n = sum(1 for x in rows if x["kind"] == "post" and x.get("status") != "wiped" and sub in (x.get("collections") or "").split(";"))
            node = entry_node(r["telegraph_url"], r["title"], local_date(r["created_at"]), 0,
                              ["collection"] + ([cols[sub]["run"].lower()] if cols[sub].get("run") else []),
                              f"{n} {'post' if n == 1 else 'posts'}. {cols[sub]['about']}")
        else:
            continue
        items.append((r["created_at"], node))
    items.sort(key=lambda x: x[0], reverse=c.get("display") != "stream")
    head = [{"tag": "p", "children": [c["about"]]}]
    listing = [{"tag": "ul", "children": [n for _, n in items]}] if items else [{"tag": "p", "children": ["Nothing here yet."]}]
    title = "HeavyMap Journey" if key == "journey" else c["name"]
    page = edit_page(access_token=tok, path=c["path"], title=title, author_name="HeavyMap", author_url="https://heavymap.com/journey",
                     content=json.dumps(head + listing + [marker(key != "journey")], ensure_ascii=False))
    save_copy(page)
    print(f"  index {c['name']}: {len(items)} entries")


def cmd_rebuild(args) -> None:
    tok, cols = token(), collections()
    for key in args.keys or [k for k in cols if k != "journey"]:
        rebuild_index(key, tok)


