import test from "node:test";
import assert from "node:assert/strict";
import { parseIndex, parsePost, safeUrl, sanitize, telegraphPath } from "../src/journey/telegraph.js";

const index = [
  { tag: "p", children: ["Where HeavyMap came from."] },
  { tag: "ul", children: [
    { tag: "li", children: [
      { tag: "a", attrs: { href: "https://telegra.ph/What-Hamilton-taught-us-11-19" }, children: ["What Hamilton taught us"] },
      " — 2026-11-19 · 7 min · expansion, retro, hamilton",
      { tag: "br" },
      "Our first city was mapped before we had a method.",
    ] },
    { tag: "li", children: [{ tag: "a", attrs: { href: "https://example.com/x" }, children: ["Elsewhere"] }, " — 2026-11-18"] },
  ] },
  { tag: "p", children: ["Index generated by Telepatch. byline=plain collection=extra"] },
];

test("index entries keep Telepatch's meta line", () => {
  const { entries, intro, curated } = parseIndex(index);
  assert.equal(curated, true);
  assert.equal(intro.length, 1);
  assert.deepEqual(entries[0], {
    title: "What Hamilton taught us",
    url: "https://telegra.ph/What-Hamilton-taught-us-11-19",
    path: "What-Hamilton-taught-us-11-19",
    date: "2026-11-19",
    minutes: 7,
    tags: ["expansion", "retro", "hamilton"],
    excerpt: "Our first city was mapped before we had a method.",
  });
  assert.equal(entries[1].path, null);
  assert.equal(entries[1].minutes, 0);
});

test("an empty index has no entries", () => {
  const { entries } = parseIndex([{ tag: "p", children: ["Nothing here yet."] }, { tag: "p", children: ["Index generated by Telepatch. byline=plain"] }]);
  assert.deepEqual(entries, []);
});

test("posts split into tags, standfirst, body and a hidden colophon", () => {
  const post = parsePost([
    { tag: "aside", children: ["expansion, retro, hamilton"] },
    { tag: "blockquote", children: ["A one-line result."] },
    { tag: "h3", children: ["What we did"] },
    { tag: "p", children: ["Body."] },
    { tag: "h3", children: ["Next"] },
    { tag: "p", children: [{ tag: "em", children: ["Prepared with Claude (Anthropic) · model Claude Opus 5.5 · 2026-11-19"] }] },
    { tag: "hr" },
    { tag: "pre", children: ["heavymap-journey/1\nid: JP-0005\ntype: retro\nrun: CR-001"] },
  ]);
  assert.deepEqual(post.tags, ["expansion", "retro", "hamilton"]);
  assert.equal(post.intro.tag, "blockquote");
  assert.deepEqual(post.colophon, { id: "JP-0005", type: "retro", run: "CR-001" });
  assert.equal(post.body.length, 4);
  assert.deepEqual(post.sections.map((s) => s.text), ["What we did", "Next"]);
});

test("only safe tags and URLs survive", () => {
  const out = sanitize([
    { tag: "script", children: ["alert(1)"] },
    { tag: "a", attrs: { href: "javascript:alert(1)" }, children: ["bad"] },
    { tag: "img", attrs: { src: "/file/abc.jpg" } },
    { tag: "img", attrs: { src: "http://insecure.example/x.png" } },
    { tag: "iframe", attrs: { src: "https://telegra.ph/embed/youtube?url=x" } },
  ]);
  assert.deepEqual(out, [
    "alert(1)",
    "bad",
    { tag: "img", src: "https://telegra.ph/file/abc.jpg", children: [] },
    { tag: "a", href: "https://telegra.ph/embed/youtube?url=x", children: ["Embedded media"] },
  ]);
});

test("links to our own posts are routed inside /journey", () => {
  const out = sanitize([{ tag: "a", attrs: { href: "https://telegra.ph/Starting-El-Segundo-11-19" }, children: ["next"] }], {
    route: (href) => (telegraphPath(href) === "Starting-El-Segundo-11-19" ? "/journey/expansion/#Starting-El-Segundo-11-19" : null),
  });
  assert.equal(out[0].href, "/journey/expansion/#Starting-El-Segundo-11-19");
  assert.equal(out[0].internal, true);
});

test("telegraph paths and URLs", () => {
  assert.equal(telegraphPath("https://telegra.ph/Some-Page-11-19"), "Some-Page-11-19");
  assert.equal(telegraphPath("https://telegra.ph/file/abc.jpg"), null);
  assert.equal(telegraphPath("https://example.com/Some-Page"), null);
  assert.equal(safeUrl("data:text/html,x"), null);
});
